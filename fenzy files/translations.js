// Get user's language based on IP geolocation
async function detectUserLanguage() {
    try {
        // Check if language is stored in localStorage
        const savedLang = localStorage.getItem('fenzy-language');
        if (savedLang && translations[savedLang]) {
            return savedLang;
        }

        // Try to get country from IP using ipapi.co (free, no API key required)
        const response = await fetch('https://ipapi.co/json/');
        const data = await response.json();

        if (data && data.country_code) {
            const countryCode = data.country_code;
            const language = countryLanguageMap[countryCode] || 'en';

            // Save detected language
            localStorage.setItem('fenzy-language', language);
            localStorage.setItem('fenzy-country', countryCode);

            return language;
        }
    } catch (error) {
        console.log('IP detection failed, using browser language');
    }

    // Fallback to browser language
    const browserLang = navigator.language || navigator.userLanguage;
    const langCode = browserLang.split('-')[0];

    if (translations[langCode]) {
        return langCode;
    }

    return 'en'; // Default to English
}

