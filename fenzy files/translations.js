// Apply translations to the page
function applyTranslations(lang) {
    const texts = translations[lang] || translations.en;

    // Update HTML lang attribute
    document.documentElement.lang = lang;

    // Update dir attribute for RTL languages
    if (lang === 'ar') {
        document.documentElement.dir = 'rtl';
        document.body.style.fontFamily = "'Arial', 'Tahoma', sans-serif";
    } else {
        document.documentElement.dir = 'ltr';
        document.body.style.fontFamily = "";
    }

    // Method 1: Translate all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (texts[key]) {
            // Handle different element types
            if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                element.placeholder = texts[key];
            } else {
                element.textContent = texts[key];
            }
        }
    });

    // Method 2: Auto-translate by matching text content
    const walkTextNodes = (node) => {
        if (node.nodeType === Node.TEXT_NODE) {
            const trimmedText = node.textContent.trim();
            if (trimmedText && textMapping[trimmedText]) {
                const key = textMapping[trimmedText];
                if (texts[key]) {
                    node.textContent = node.textContent.replace(trimmedText, texts[key]);
                }
            }
        } else if (node.nodeType === Node.ELEMENT_NODE && !node.hasAttribute('data-no-translate')) {
            // Skip script tags, style tags, and elements with data-no-translate
            if (!['SCRIPT', 'STYLE', 'NOSCRIPT'].includes(node.tagName)) {
                for (const child of node.childNodes) {
                    walkTextNodes(child);
                }
            }
        }
    };

    // Walk through all text nodes and translate
    walkTextNodes(document.body);

    // Update language selector if exists
    const languageSelector = document.getElementById('language-selector');
    if (languageSelector) {
        languageSelector.value = lang;
    }

    console.log(`Language changed to: ${lang}`);
}

// Change language manually
function changeLanguage(lang) {
    if (translations[lang]) {
        localStorage.setItem('fenzy-language', lang);
        applyTranslations(lang);
    }
}

// Initialize translation system
async function initTranslation() {
    const userLang = await detectUserLanguage();
    applyTranslations(userLang);
}

